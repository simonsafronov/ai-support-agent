_ASK_CONTACT = re.compile(r"(?i)\b(?:почт\w*|e-?mail)\s+(?:или|либо|or)\s+(?:номер\s+)?(?:телефон|phone)"
                          r"|\b(?:телефон\w*|phone(?: number)?)\s+(?:или|либо|or)\s+(?:почт|e-?mail)"
                          r"|контакт\w*\s+для\s+связи")


def _contact_asked(session: dict) -> bool:
    """Агент уже просил контакт в каком-то из своих ответов: просьба в каждом ответе клиента раздражает."""
    return bool(session.get("id")) and any(
        m["role"] == "assistant" and _ASK_CONTACT.search(m["content"]) for m in store.messages(session["id"]))


def _price(p) -> str:
    return f"{p:,.2f} руб.".replace(",", " ") if p else "цена по запросу"


def system_prompt(session: dict, page_hint: str = "", previous: dict | None = None) -> str:
    return SYSTEM + "\n\nКОНТЕКСТ\n" + context_block(session, page_hint, previous)
