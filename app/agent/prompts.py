def context_block(session: dict, page_hint: str = "", previous: dict | None = None) -> str:
    """Что агент знает к началу хода: дата, страница, память о клиенте, уже обсужденные позиции."""
    lines = [f"Сегодня {datetime.date.today():%d.%m.%Y}."]
    if page_hint:
        lines.append(page_hint)
    if session.get("facts"):
        lines.append("Известно о клиенте: " + "; ".join(f"{k}: {v}" for k, v in session["facts"].items()) + ".")
    items = session.get("items") or {}
    if items.get("products"):
        lines.append("Продукты, которые уже находили в этом диалоге (product_id: название): "
                     + "; ".join(f"{p['id']}: {p['title']}" for p in items["products"]) + ".")
    if items.get("offers"):
        lines.append("Варианты, которые уже показывали (offer_id: название, цена): "
                     + "; ".join(f"{o['id']}: {o['name']}, {_price(o.get('price'))}" for o in items["offers"]) + ".")
    if session.get("status") == "handoff":
        lines.append("Обращение уже передано менеджеру. На простые вопросы продолжайте отвечать, повторно не передавайте.")
    if previous and (previous.get("facts") or (previous.get("items") or {}).get("offers")):
        prev = []
        if previous.get("facts"):
            prev.append("о клиенте: " + "; ".join(f"{k}: {v}" for k, v in previous["facts"].items()))
        offers = (previous.get("items") or {}).get("offers") or []
        if offers:
            prev.append("обсуждали: " + "; ".join(o["name"] for o in offers[:3]))
        lines.append("Клиент уже обращался раньше (" + ", ".join(prev) + "). Можно сослаться на это, не переспрашивая.")
    return "\n".join(lines)


def _price(p) -> str:
    return f"{p:,.2f} руб.".replace(",", " ") if p else "цена по запросу"


def system_prompt(session: dict, page_hint: str = "", previous: dict | None = None) -> str:
    return SYSTEM + "\n\nКОНТЕКСТ\n" + context_block(session, page_hint, previous)
