def procedure(text):
    return next((p for p in PROCEDURES if p.applies(text)), None)


def buyer_procedure(query):
    return not choosing_software(query) and procedure(query) is not None


def choosing_software(query):
    return bool(re.search(r'(?=.*\b(?:софт|программ\w*|приложени\w*|редактор\w*)\b)'
                          r'(?=.*\b(?:подбор|подобра\w*|найти|ищу|выб\w*|какую|какое|посовет\w*|порекоменд\w*)\b)', query, re.I))


def support_followup(query, previous_user=''):
    """A report about a support step, not a request to select a new product."""
    issue = r'активац|ошибк|сбо[йя]|неисправност|проблем|не запуска|не работа'
    if not re.search(issue, query + ' ' + previous_user, re.I) or '?' in query or re.search(r'\b(?:если|чтобы)\b', query, re.I):
        return None
    if re.search(r'остал[а-яё]*|сохраняется|по-прежнему|вс[её] равно|не помог|не заработал|не исчез', query, re.I):
        return ('Похоже, предыдущий шаг не устранил ошибку. Напишите текст ошибки и версию программы, без '
                'лицензионного ключа. Если нужна проверка вашей лицензии, можно подключить менеджера.')
    if re.search(r'\b(?:заработал\w*|получилось|исправил\w*|решен[ао]?|исчезла)\b', query, re.I) and not re.search(r'\b(?:не|если|но|чтобы|когда)\b', query, re.I):
        return 'Хорошо, что всё заработало. Если ошибка не возвращается, больше ничего делать не нужно.'
    return None
