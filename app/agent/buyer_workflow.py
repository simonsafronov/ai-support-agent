"""Buyer procedures: distinguish what the buyer wants to do from generic word overlap.

The patterns identify the procedure, not the answer. Payment methods, availability,
terms and store channels may only come from an eligible public article.
"""
import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Procedure:
    intent: str
    evidence: str
    next_step: str

    def applies(self, text):
        return bool(re.search(self.intent, text, re.I))

    def supports(self, body):
        return bool(re.search(self.evidence, body, re.I))


